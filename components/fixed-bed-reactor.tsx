const FixedBedReactor = (props: {
  width: number;
  height: number;
  controls: number[];
}) => {
  const { width, height, controls } = props;

  const numInteravls = controls.length;
  const xScale = scaleLinear().range([0, width]).domain([0, 1]);
  const yScale = scaleLinear().range([height, 0]).domain([0, 1]);

  const colorScale = scaleSequential(
    [0, 1],
    ["oklch(70.4% 0.14 182.503)", "oklch(60.6% 0.25 292.717)"],
  );

  const fillScale = scaleSequential(
    [0, 1],
    ["oklch(95.3% 0.051 180.801)", "oklch(94.3% 0.029 294.588)"],
  );
  const getInterval = (pos: number) => {
    let idx = Math.floor(pos * numInteravls);
    if (idx === numInteravls) idx = numInteravls - 1;
    return idx;
  };

  return (
    <svg width={width} height={height} className="overflow-visible ">
      <clipPath id="fbr-clip">
        <rect x={0} y={0} width={width} height={height} rx={10} />
      </clipPath>

      <g clipPath="url(#fbr-clip)">
        {pellets.map((pellet, index) => (
          <circle
            key={`pellet-${index}`}
            cx={xScale(pellet.x)}
            cy={yScale(pellet.y)}
            r={12}
            stroke={colorScale(controls[getInterval(pellet.x)])}
            fill={fillScale(controls[getInterval(pellet.x)])}
            className="transition-colors stroke-2"
          />
        ))}
      </g>
      <rect
        x={0}
        y={0}
        width={width}
        height={height}
        fill="transparent"
        rx={10}
        className="stroke-gray-500 stroke-2"
      />

      <rect
        x={-30}
        y={height / 2 - 20}
        height={40}
        width={30}
        fill="transparent"
        className="stroke-2 stroke-gray-500"
      />

      <rect
        x={width}
        y={height / 2 - 20}
        height={40}
        width={30}
        fill="transparent"
        className="stroke-2 stroke-gray-500"
      />
    </svg>
  );
};

export default FixedBedReactor;
